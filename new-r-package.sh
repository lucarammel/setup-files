#!/usr/bin/env bash
set -e

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ -z "$1" ] || [ -z "$2" ]; then
  echo "Usage: $0 <nom-du-package> <dossier-parent>"
  exit 1
fi

PACKAGE_NAME="$1"
PACKAGE_NAME_R=$(echo "$PACKAGE_NAME" | tr '-' '.')
PARENT_DIR="$2"
PROJECT_DIR="$PARENT_DIR/$PACKAGE_NAME"

echo "Création de $PROJECT_DIR..."
mkdir -p "$PROJECT_DIR"
cd "$PROJECT_DIR"

# Git
git init

# Structure package
mkdir -p R tests/testthat

cat > DESCRIPTION <<EOF
Package: $PACKAGE_NAME_R
Type: Package
Title: What the Package Does
Version: 0.1.0
Description: What the package does.
License: MIT + file LICENSE
Encoding: UTF-8
Roxygen: list(markdown = TRUE)
RoxygenNote: 7.3.2
Suggests:
    testthat (>= 3.0.0)
Config/testthat/edition: 3
EOF

echo "# Generated by roxygen2: do not edit by hand" > NAMESPACE

cat > "R/$PACKAGE_NAME_R.R" <<'EOF'
#' @keywords internal
"_PACKAGE"
EOF

# renv + scaffold en une seule session R
echo "Initialisation de renv..."
Rscript - <<'REOF'
if (!requireNamespace("renv", quietly = TRUE)) {
  install.packages("renv", repos = "https://cloud.r-project.org")
}
renv::init(bare = TRUE)
renv::install(c("usethis", "devtools", "testthat", "roxygen2", "rlang", "data.table", "dplyr", "lubridate"))
library(usethis)
use_mit_license()
use_testthat()
use_package("dplyr")
use_package("data.table")
use_package("lubridate")
use_package("rlang")
renv::snapshot(prompt = FALSE)
REOF

# Configs communes
cp "$REPO_DIR/templates/README.md" .
sed -i '' "s/mon-projet/$PACKAGE_NAME/g" README.md
cp "$REPO_DIR/templates/.gitignore-r" .gitignore
cp -r "$REPO_DIR/templates/.zed" .

git add .
git commit -m "init: $PACKAGE_NAME"

echo ""
echo "Package R créé : $PROJECT_DIR"
echo ""
echo "  Rscript -e 'devtools::load_all()'"
echo "  Rscript -e 'devtools::test()'"
echo "  Rscript -e 'devtools::document()'"
echo "  Rscript -e 'devtools::check()'"
echo "  air format ."
echo "  zed ."
